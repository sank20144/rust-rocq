use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use crate::rocq::Term;

pub struct Output {
    pub dir: PathBuf,
    entries: Vec<(String, Term)>,
    adts: Vec<Term>,
    traits: Vec<Term>,
    impls: Vec<Term>,
    mir: String,
    flags: Vec<(&'static str, String)>,
}

impl Output {
    pub fn new(dir: impl Into<PathBuf>) -> Self {
        Output {
            dir: dir.into(),
            entries: Vec::new(),
            adts: Vec::new(),
            traits: Vec::new(),
            impls: Vec::new(),
            mir: String::new(),
            flags: Vec::new(),
        }
    }

    pub fn push(&mut self, name: String, body: Term) {
        self.entries.push((name, body));
    }

    pub fn push_mir(&mut self, name: &str, mir: String) {
        self.mir.push_str(&format!("// ---- {name} ----\n{mir}\n"));
    }

    pub fn set_items(&mut self, adts: Vec<Term>, traits: Vec<Term>, impls: Vec<Term>) {
        self.adts = adts;
        self.traits = traits;
        self.impls = impls;
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
            && self.adts.is_empty()
            && self.traits.is_empty()
            && self.impls.is_empty()
    }

    pub fn set_build_flags(&mut self, flags: Vec<(&'static str, String)>) {
        self.flags = flags;
    }

    pub fn write(mut self, crate_name: &str, source: &str) -> std::io::Result<PathBuf> {
        std::fs::create_dir_all(&self.dir)?;
        let path = self.dir.join(format!("{}.v", ident(crate_name)));

        let mut constructors = BTreeSet::new();
        for term in &self.adts {
            term.collect_heads(&mut constructors);
        }
        for term in &self.traits {
            term.collect_heads(&mut constructors);
        }
        for term in &self.impls {
            term.collect_heads(&mut constructors);
        }
        for (_, term) in &self.entries {
            term.collect_heads(&mut constructors);
        }
        let mut body_names: Vec<_> = self.entries.iter().map(|(name, _)| name.clone()).collect();
        body_names.sort();

        let mut banner = format!("(* Generated by rust-rocq from {source}. Do not edit. *)\n");
        for (name, value) in &self.flags {
            banner.push_str(&format!("(*   {name} = {value} *)\n"));
        }

        let mut out = String::new();
        out.push_str(&banner);
        out.push_str(&format!(
            "\n\
             From RustRocq Require Import Syntax.\n\
             From Stdlib Require Import String List ZArith.\n\
             Import ListNotations.\n\
             Local Open Scope string_scope.\n\n"
        ));
        let _ = source;

        let adts = Term::List(std::mem::take(&mut self.adts));
        let traits = Term::List(std::mem::take(&mut self.traits));
        let impls = Term::List(std::mem::take(&mut self.impls));
        out.push_str(&format!(
            "Definition adts : list adt_def :=\n  {}.\n\n",
            adts.render_at(2)
        ));
        out.push_str(&format!(
            "Definition traits : list trait_def :=\n  {}.\n\n",
            traits.render_at(2)
        ));
        out.push_str(&format!(
            "Definition impls : list impl_def :=\n  {}.\n\n",
            impls.render_at(2)
        ));

        let mut idents = Vec::new();
        for (name, body) in &self.entries {
            let id = unique(&ident(name), &idents);
            out.push_str(&format!("Definition {id} : body :=\n  {}.\n\n", body.render_at(2)));
            idents.push(id);
        }

        out.push_str(&format!(
            "Definition bodies : list body := [{}].\n",
            idents.join("; ")
        ));

        std::fs::write(&path, out)?;

        let mir_path = path.with_extension("mir");
        std::fs::write(
            &mir_path,
            format!(
                "// MIR at Analysis(Initial) for {source}, as translated into {}.\n\
                 // Region numbers match the RVar and origin numbers in the Rocq file.\n\n{}",
                path.file_name().unwrap_or_default().to_string_lossy(),
                self.mir
            ),
        )?;

        let constructs_path = path.with_extension("constructs");
        let mut constructs = constructors.into_iter().collect::<Vec<_>>().join("\n");
        if !constructs.is_empty() {
            constructs.push('\n');
        }
        std::fs::write(constructs_path, constructs)?;

        let bodies_path = path.with_extension("bodies");
        let mut bodies = body_names.join("\n");
        if !bodies.is_empty() {
            bodies.push('\n');
        }
        std::fs::write(bodies_path, bodies)?;

        Ok(path)
    }
}

fn ident(path: &str) -> String {
    let mut s: String = path
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    while s.contains("__") {
        s = s.replace("__", "_");
    }
    let s = s.trim_matches('_').to_owned();
    if s.is_empty() || s.starts_with(|c: char| c.is_ascii_digit()) {
        format!("item_{s}")
    } else {
        s
    }
}

fn unique(base: &str, taken: &[String]) -> String {
    if !taken.iter().any(|t| t == base) {
        return base.to_owned();
    }
    (1..).map(|n| format!("{base}_{n}")).find(|c| !taken.contains(c)).unwrap()
}

pub fn source_name(path: &Path) -> String {
    path.file_name().map_or_else(|| "input".to_owned(), |n| n.to_string_lossy().into_owned())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn paths_become_identifiers() {
        assert_eq!(ident("simple::add"), "simple_add");
        assert_eq!(ident("<Foo as Bar>::baz"), "Foo_as_Bar_baz");
        assert_eq!(ident("9lives"), "item_9lives");
    }

    #[test]
    fn collisions_get_a_suffix() {
        let taken = vec!["f".to_owned(), "f_1".to_owned()];
        assert_eq!(unique("f", &taken), "f_2");
        assert_eq!(unique("g", &taken), "g");
    }
}
