use std::path::{Path, PathBuf};

use crate::rocq::Term;

pub struct Output {
    pub dir: PathBuf,
    entries: Vec<(String, Term)>,
}

impl Output {
    pub fn new(dir: impl Into<PathBuf>) -> Self {
        Output { dir: dir.into(), entries: Vec::new() }
    }

    pub fn push(&mut self, name: String, body: Term) {
        self.entries.push((name, body));
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    pub fn write(&self, crate_name: &str, source: &str) -> std::io::Result<PathBuf> {
        std::fs::create_dir_all(&self.dir)?;
        let path = self.dir.join(format!("{}.v", ident(crate_name)));

        let mut out = String::new();
        out.push_str(&format!(
            "(* Generated by rust-rocq from {source}. Do not edit. *)\n\n\
             From RustRocq Require Import Syntax.\n\
             From Stdlib Require Import String List ZArith.\n\
             Import ListNotations.\n\
             Local Open Scope string_scope.\n\n"
        ));

        let mut idents = Vec::new();
        for (name, body) in &self.entries {
            let id = unique(&ident(name), &idents);
            out.push_str(&format!("Definition {id} : body :=\n  {}.\n\n", body.render()));
            idents.push(id);
        }

        out.push_str(&format!(
            "Definition bodies : list body := [{}].\n",
            idents.join("; ")
        ));

        std::fs::write(&path, out)?;
        Ok(path)
    }
}

fn ident(path: &str) -> String {
    let mut s: String = path
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    while s.contains("__") {
        s = s.replace("__", "_");
    }
    let s = s.trim_matches('_').to_owned();
    if s.is_empty() || s.starts_with(|c: char| c.is_ascii_digit()) {
        format!("item_{s}")
    } else {
        s
    }
}

fn unique(base: &str, taken: &[String]) -> String {
    if !taken.iter().any(|t| t == base) {
        return base.to_owned();
    }
    (1..).map(|n| format!("{base}_{n}")).find(|c| !taken.contains(c)).unwrap()
}

pub fn source_name(path: &Path) -> String {
    path.file_name().map_or_else(|| "input".to_owned(), |n| n.to_string_lossy().into_owned())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn paths_become_identifiers() {
        assert_eq!(ident("simple::add"), "simple_add");
        assert_eq!(ident("<Foo as Bar>::baz"), "Foo_as_Bar_baz");
        assert_eq!(ident("9lives"), "item_9lives");
    }

    #[test]
    fn collisions_get_a_suffix() {
        let taken = vec!["f".to_owned(), "f_1".to_owned()];
        assert_eq!(unique("f", &taken), "f_2");
        assert_eq!(unique("g", &taken), "g");
    }
}
